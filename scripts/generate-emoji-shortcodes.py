#!/usr/bin/env python3
"""Generates src/editor/emoji_shortcodes_data.inc, the note editor's emoji picker list.

The list is taken from the markdown-it-emoji build the Markdown preview renders with
(pinned in CMakeLists.txt, downloaded by FetchContent), so every shortcode the picker
offers is one the preview turns into an emoji. Its data is GitHub's gemoji set: every
Unicode emoji GitHub knows by `:name:`, aliases included, in gemoji's category order.
GitHub's few image-only names (`:octocat:`, `:shipit:`, ...) have no Unicode character,
so neither the plugin nor the picker has them.

Run it after changing the markdown-it-emoji pin, commit the regenerated file, rebuild:

    ./scripts/generate-emoji-shortcodes.py [path/to/markdown-it-emoji.min.js]

The default path is the one a configured `build/` directory holds.
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = ROOT / "build/_deps/nekogrid_markdown_it_emoji-src/markdown-it-emoji.min.js"
OUTPUT = ROOT / "src/editor/emoji_shortcodes_data.inc"

# One `key:"value"` pair of the bundle's definitions object. Keys are bare identifiers,
# numbers (100, 1234) or quoted ("+1", "-1"); values are JS strings of \u escapes.
PAIR = re.compile(r'(?:"([^"]+)"|([A-Za-z0-9_$]+)):"((?:[^"\\]|\\.)*)"')
NAME = re.compile(r"^[a-z0-9_+-]+$")


def definitions(bundle: str) -> list[tuple[str, str]]:
    start = bundle.index("var a={") + len("var a={")
    end = bundle.index("}", start)  # values are escapes only: the first '}' ends it
    body = bundle[start:end]
    pairs = []
    pos = 0
    while pos < len(body):
        m = PAIR.match(body, pos)
        if not m:
            raise SystemExit(f"unexpected definitions syntax near: {body[pos:pos + 60]!r}")
        name = m.group(1) or m.group(2)
        # JS's \xNN is JSON's \u00NN; json joins the surrogate pairs.
        emoji = json.loads('"' + re.sub(r"\\x([0-9A-Fa-f]{2})", r"\\u00\1", m.group(3)) + '"')
        if not NAME.match(name):
            raise SystemExit(f"unexpected shortcode name: {name!r}")
        pairs.append((name, emoji))
        pos = m.end()
        if pos < len(body):
            if body[pos] != ",":
                raise SystemExit(f"expected ',' near: {body[pos:pos + 60]!r}")
            pos += 1
    return pairs


def c_string(text: str) -> str:
    return '"' + "".join(f"\\x{b:02X}" for b in text.encode("utf-8")) + '"'


def main() -> None:
    source = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SOURCE
    bundle = source.read_text(encoding="utf-8")
    version = re.search(r"markdown-it-emoji (\d+\.\d+\.\d+)", bundle)
    pairs = definitions(bundle)
    if len(pairs) < 1000 or len({n for n, _ in pairs}) != len(pairs):
        raise SystemExit(f"implausible definitions: {len(pairs)} entries")

    lines = [
        "// Generated by scripts/generate-emoji-shortcodes.py from markdown-it-emoji "
        f"{version.group(1) if version else '?'} -- do not edit.",
        f"// {len(pairs)} shortcodes (GitHub's gemoji set), in gemoji's category order.",
        "// clang-format off",
    ]
    for name, emoji in pairs:
        lines.append(f'{{"{name}", {c_string(emoji)}}},')
    lines.append("// clang-format on")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(pairs)} shortcodes)")


if __name__ == "__main__":
    main()
